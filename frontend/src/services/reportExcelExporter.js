/**
 * iSysware HRMS — F14 Professional Excel Export Engine
 * Generates Chartered Accountant-grade styled .xlsx workbooks using ExcelJS.
 * Zero charts — strict tabular compliance, navy branding, frozen panes, and accounting formats.
 */

import ExcelJS from 'exceljs'

/**
 * Sanitize text to prevent formula injection in Excel
 */
function sanitizeExcelValue(val) {
  if (typeof val === 'string') {
    const trimmed = val.trim()
    if (['=', '+', '-', '@'].some((char) => trimmed.startsWith(char))) {
      return `'${trimmed}`
    }
    return trimmed
  }
  return val
}

export const reportExcelExporter = {
  /**
   * Builds an ExcelJS Workbook with CA-standard styling
   */
  async buildWorkbook(reportResult) {
    const { report, columns, rows, totals, metadata } = reportResult
    const workbook = new ExcelJS.Workbook()
    workbook.creator = 'iSysware HRMS Enterprise Suite'
    workbook.lastModifiedBy = metadata?.generatedBy || 'System Admin'
    workbook.created = new Date()
    workbook.modified = new Date()

    const sheetName = (report.name || 'Report').slice(0, 31).replace(/[:\\/?*[\]]/g, '')
    const worksheet = workbook.addWorksheet(sheetName, {
      pageSetup: {
        paperSize: 9, // A4
        orientation: columns.length > 7 ? 'landscape' : 'portrait',
        fitToPage: true,
        fitToWidth: 1,
        fitToHeight: 0
      }
    })

    const totalCols = Math.max(columns.length, 6)

    // Palette tokens
    const NAVY_HEADER = 'FF102746'
    const WHITE_TEXT = 'FFFFFFFF'
    const ALT_ROW_FILL = 'FFF4F8FA'
    const TOTAL_FILL = 'FFE2E8F0'
    const BORDER_COLOR = 'FFCBD5E1'

    const thinBorder = {
      top: { style: 'thin', color: { argb: BORDER_COLOR } },
      left: { style: 'thin', color: { argb: BORDER_COLOR } },
      bottom: { style: 'thin', color: { argb: BORDER_COLOR } },
      right: { style: 'thin', color: { argb: BORDER_COLOR } }
    }

    // ----------------------------------------------------
    // ROW 1: COMPANY BRANDING (Merged, Navy #102746, Bold White)
    // ----------------------------------------------------
    worksheet.mergeCells(1, 1, 1, totalCols)
    const row1 = worksheet.getRow(1)
    row1.height = 36
    const cell1 = row1.getCell(1)
    cell1.value = 'iSysware Software Solutions — Corporate Human Resource Management'
    cell1.font = { name: 'Calibri', size: 14, bold: true, color: { argb: WHITE_TEXT } }
    cell1.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: NAVY_HEADER } }
    cell1.alignment = { horizontal: 'center', vertical: 'middle' }

    // ----------------------------------------------------
    // ROW 2: SPACING
    // ----------------------------------------------------
    worksheet.getRow(2).height = 10

    // ----------------------------------------------------
    // ROW 3: REPORT TITLE
    // ----------------------------------------------------
    worksheet.mergeCells(3, 1, 3, totalCols)
    const row3 = worksheet.getRow(3)
    row3.height = 24
    const cell3 = row3.getCell(1)
    cell3.value = (report.name || 'REPORT').toUpperCase()
    cell3.font = { name: 'Calibri', size: 13, bold: true, color: { argb: NAVY_HEADER } }
    cell3.alignment = { horizontal: 'center', vertical: 'middle' }

    // ----------------------------------------------------
    // ROWS 4-6: METADATA INFORMATION BLOCK
    // ----------------------------------------------------
    const metaRows = [
      [
        'Reporting Period:',
        metadata?.periodLabel || 'Current Period',
        '',
        'Applied Filters:',
        `Dept: ${metadata?.appliedFilters?.department || 'All'} | Scope: ${metadata?.appliedFilters?.employee || 'All'}`
      ],
      [
        'Report Reference:',
        `${report.id} (${report.familyId})`,
        '',
        'Generated Date & Time:',
        metadata?.generatedAtFormatted || new Date().toISOString()
      ],
      [
        'Generated By:',
        metadata?.generatedBy || 'Authorized Officer',
        '',
        'Confidentiality Notice:',
        metadata?.confidentialityNotice || 'STRICTLY CONFIDENTIAL'
      ]
    ]

    let currentRowIdx = 4
    metaRows.forEach((rData) => {
      const r = worksheet.getRow(currentRowIdx)
      r.height = 18

      // Left pair
      const lLabel = r.getCell(1)
      lLabel.value = rData[0]
      lLabel.font = { name: 'Calibri', size: 9, bold: true, color: { argb: 'FF475569' } }
      const lVal = r.getCell(2)
      lVal.value = rData[1]
      lVal.font = { name: 'Calibri', size: 9, color: { argb: 'FF0F172A' } }

      // Right pair (columns 4 and 5)
      const rLabel = r.getCell(4)
      rLabel.value = rData[3]
      rLabel.font = { name: 'Calibri', size: 9, bold: true, color: { argb: 'FF475569' } }
      const rVal = r.getCell(5)
      rVal.value = rData[4]
      rVal.font = { name: 'Calibri', size: 9, color: { argb: 'FF0F172A' } }

      currentRowIdx++
    })

    // ROW 7: Empty space before table
    worksheet.getRow(7).height = 12

    // ----------------------------------------------------
    // ROW 8: DATA TABLE COLUMN HEADINGS
    // ----------------------------------------------------
    const headerRowIndex = 8
    const headerRow = worksheet.getRow(headerRowIndex)
    headerRow.height = 26

    columns.forEach((col, idx) => {
      const cell = headerRow.getCell(idx + 1)
      cell.value = col.label
      cell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: WHITE_TEXT } }
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: NAVY_HEADER } }
      cell.alignment = { horizontal: col.align || 'left', vertical: 'middle', wrapText: true }
      cell.border = thinBorder
    })

    // ----------------------------------------------------
    // DATA ROWS (Alternating subtle colors, aligned types)
    // ----------------------------------------------------
    currentRowIdx = 9

    if (!rows || rows.length === 0) {
      worksheet.mergeCells(currentRowIdx, 1, currentRowIdx, totalCols)
      const emptyRow = worksheet.getRow(currentRowIdx)
      emptyRow.height = 32
      const emptyCell = emptyRow.getCell(1)
      emptyCell.value = 'No records found matching the applied filter criteria.'
      emptyCell.font = { name: 'Calibri', size: 10, italic: true, color: { argb: 'FF64748B' } }
      emptyCell.alignment = { horizontal: 'center', vertical: 'middle' }
      emptyCell.border = thinBorder
      currentRowIdx++
    } else {
      rows.forEach((row, rIdx) => {
        const dRow = worksheet.getRow(currentRowIdx)
        dRow.height = 20
        const isAlt = rIdx % 2 === 1

        columns.forEach((col, cIdx) => {
          const cell = dRow.getCell(cIdx + 1)
          let val = row[col.key]

          if (col.type === 'currency' || col.type === 'number') {
            cell.value = Number(val) || 0
            if (col.type === 'currency') {
              cell.numFmt = '#,##0.00'
            } else {
              cell.numFmt = '#,##0'
            }
          } else {
            cell.value = sanitizeExcelValue(val !== undefined && val !== null ? val : '')
          }

          cell.font = { name: 'Calibri', size: 9.5, color: { argb: 'FF0F172A' } }
          cell.alignment = { horizontal: col.align || 'left', vertical: 'middle' }
          if (isAlt) {
            cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: ALT_ROW_FILL } }
          }
          cell.border = thinBorder
        })
        currentRowIdx++
      })
    }

    // ----------------------------------------------------
    // GRAND TOTALS ROW
    // ----------------------------------------------------
    if (rows && rows.length > 0) {
      const totRow = worksheet.getRow(currentRowIdx)
      totRow.height = 24

      columns.forEach((col, cIdx) => {
        const cell = totRow.getCell(cIdx + 1)
        if (cIdx === 0) {
          cell.value = 'GRAND TOTAL'
          cell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: 'FF0F172A' } }
          cell.alignment = { horizontal: 'left', vertical: 'middle' }
        } else if ((col.type === 'currency' || col.type === 'number') && totals && totals[col.key] !== null) {
          cell.value = Number(totals[col.key]) || 0
          cell.numFmt = col.type === 'currency' ? '#,##0.00' : '#,##0'
          cell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: 'FF0F172A' } }
          cell.alignment = { horizontal: 'right', vertical: 'middle' }
        } else {
          cell.value = ''
        }

        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: TOTAL_FILL } }
        cell.border = {
          top: { style: 'thin', color: { argb: 'FF94A3B8' } },
          bottom: { style: 'double', color: { argb: 'FF0F172A' } },
          left: { style: 'thin', color: { argb: BORDER_COLOR } },
          right: { style: 'thin', color: { argb: BORDER_COLOR } }
        }
      })
      currentRowIdx++
    }

    // ----------------------------------------------------
    // RECONCILIATION SUMMARY FOOTER NOTE
    // ----------------------------------------------------
    currentRowIdx++
    worksheet.mergeCells(currentRowIdx, 1, currentRowIdx, totalCols)
    const recRow = worksheet.getRow(currentRowIdx)
    recRow.height = 20
    const recCell = recRow.getCell(1)
    recCell.value = `Reconciliation Note: ${report.reconciliationRule || 'All source totals reconcile with canonical records.'}`
    recCell.font = { name: 'Calibri', size: 8.5, italic: true, color: { argb: 'FF475569' } }
    recCell.alignment = { horizontal: 'left', vertical: 'middle' }

    // ----------------------------------------------------
    // AUTO-FIT COLUMN WIDTHS & FREEZE PANES
    // ----------------------------------------------------
    columns.forEach((col, idx) => {
      const explicitWidth = col.width || 16
      worksheet.getColumn(idx + 1).width = Math.max(explicitWidth, 14)
    })

    // Freeze panes right under header row
    worksheet.views = [
      {
        state: 'frozen',
        xSplit: 0,
        ySplit: headerRowIndex,
        topLeftCell: `A${headerRowIndex + 1}`,
        activeCell: `A${headerRowIndex + 1}`
      }
    ]

    // AutoFilter across table columns
    if (rows && rows.length > 0) {
      worksheet.autoFilter = {
        from: { row: headerRowIndex, column: 1 },
        to: { row: currentRowIdx - 2, column: columns.length }
      }
    }

    return workbook
  },

  /**
   * Generates and downloads the Excel (.xlsx) file in browser
   */
  async downloadExcel(reportResult) {
    const workbook = await this.buildWorkbook(reportResult)
    const buffer = await workbook.xlsx.writeBuffer()

    const reportCode = (reportResult.report.name || 'Report').replace(/[^a-zA-Z0-9]/g, '_')
    const timestamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19)
    const filename = `iSysware_${reportCode}_${timestamp}.xlsx`

    if (typeof window !== 'undefined' && typeof document !== 'undefined') {
      const blob = new Blob([buffer], {
        type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
      })
      const url = URL.createObjectURL(blob)
      const link = document.createElement('a')
      link.href = url
      link.download = filename
      document.body.appendChild(link)
      link.click()
      document.body.removeChild(link)
      URL.revokeObjectURL(url)
    }

    return { filename, bufferSize: buffer.byteLength, buffer }
  }
}
