/**
 * iSysware HRMS — F14 Professional PDF Export Engine
 * Generates Chartered Accountant-grade PDF statements using jsPDF and jspdf-autotable.
 * Features:
 * - A4 Portrait / Landscape layout adaptation based on column density
 * - Deep navy branding (#102746) & centered titles
 * - Multi-page pagination with repeated table headers (showHead: 'everyPage')
 * - Accounting-aligned columns (text left, dates center, currency right)
 * - Page X of Y numbering and confidentiality watermarking
 * - Zero charts/graphs
 */

import { jsPDF } from 'jspdf'
import autoTable from 'jspdf-autotable'

export const reportPdfExporter = {
  /**
   * Builds a jsPDF document instance with CA-standard styling
   */
  buildPdfDocument(reportResult) {
    const { report, columns, rows, totals, metadata } = reportResult
    const isLandscape = columns.length > 6
    const doc = new jsPDF({
      orientation: isLandscape ? 'landscape' : 'portrait',
      unit: 'mm',
      format: 'a4'
    })

    const pageWidth = doc.internal.pageSize.getWidth()
    const pageHeight = doc.internal.pageSize.getHeight()

    // ----------------------------------------------------
    // HEADER BLOCK: COMPANY BRANDING & TITLE
    // ----------------------------------------------------
    doc.setFillColor(16, 39, 70) // Navy #102746
    doc.rect(0, 0, pageWidth, 16, 'F')

    doc.setFont('helvetica', 'bold')
    doc.setFontSize(13)
    doc.setTextColor(255, 255, 255)
    doc.text('iSysware Software Solutions', pageWidth / 2, 8, { align: 'center' })

    doc.setFontSize(8)
    doc.setFont('helvetica', 'normal')
    doc.text('CORPORATE HUMAN RESOURCE MANAGEMENT SYSTEM — AUDIT STATEMENT', pageWidth / 2, 13, { align: 'center' })

    // Report Title
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(13)
    doc.setTextColor(16, 39, 70)
    doc.text((report.name || 'REPORT').toUpperCase(), pageWidth / 2, 24, { align: 'center' })

    // Report Subtitle / Purpose
    doc.setFont('helvetica', 'italic')
    doc.setFontSize(8)
    doc.setTextColor(100, 116, 139)
    doc.text(report.description || '', pageWidth / 2, 28, { align: 'center' })

    // ----------------------------------------------------
    // METADATA GRID (Period, Scope, Generated By, Filters)
    // ----------------------------------------------------
    doc.setDrawColor(226, 232, 240)
    doc.setFillColor(248, 250, 252)
    doc.roundedRect(10, 31, pageWidth - 20, 14, 1.5, 1.5, 'FD')

    doc.setFontSize(7.5)
    doc.setTextColor(71, 85, 105)
    doc.setFont('helvetica', 'bold')
    doc.text('Reporting Period:', 14, 35)
    doc.text('Applied Filters:', 14, 41)
    doc.text('Report Reference:', (pageWidth / 2) + 10, 35)
    doc.text('Generated By / Date:', (pageWidth / 2) + 10, 41)

    doc.setFont('helvetica', 'normal')
    doc.setTextColor(15, 23, 42)
    doc.text(metadata?.periodLabel || 'Current Period', 42, 35)
    doc.text(
      `Dept: ${metadata?.appliedFilters?.department || 'All'} | Scope: ${metadata?.appliedFilters?.employee || 'All'}`,
      42,
      41
    )
    doc.text(`${report.id} (${report.familyId})`, (pageWidth / 2) + 44, 35)
    doc.text(`${metadata?.generatedBy || 'Admin'} | ${metadata?.generatedAtFormatted || ''}`, (pageWidth / 2) + 44, 41)

    // ----------------------------------------------------
    // PREPARE TABLE DATA
    // ----------------------------------------------------
    const head = [columns.map((col) => col.label)]

    const body = rows && rows.length > 0
      ? rows.map((row) =>
          columns.map((col) => {
            const val = row[col.key]
            if (col.type === 'currency' && typeof val === 'number') {
              return val.toLocaleString('en-PK', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
            }
            if (col.type === 'number' && typeof val === 'number') {
              return val.toLocaleString('en-PK')
            }
            return val !== undefined && val !== null ? String(val) : ''
          })
        )
      : [[
          {
            content: 'No records found matching the selected filter criteria.',
            colSpan: columns.length,
            styles: { halign: 'center', fontStyle: 'italic', textColor: [100, 116, 139] }
          }
        ]]

    // Footer row for Grand Totals
    const foot = []
    if (rows && rows.length > 0) {
      const footRow = columns.map((col, cIdx) => {
        if (cIdx === 0) return 'GRAND TOTAL'
        if ((col.type === 'currency' || col.type === 'number') && totals && totals[col.key] !== null) {
          const tVal = Number(totals[col.key]) || 0
          return col.type === 'currency'
            ? tVal.toLocaleString('en-PK', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
            : tVal.toLocaleString('en-PK')
        }
        return ''
      })
      foot.push(footRow)
    }

    // Column styles alignment mapping
    const columnStyles = {}
    columns.forEach((col, idx) => {
      columnStyles[idx] = {
        halign: col.align || 'left',
        cellWidth: 'auto'
      }
    })

    // ----------------------------------------------------
    // RENDER AUTOTABLE
    // ----------------------------------------------------
    autoTable(doc, {
      head,
      body,
      foot,
      startY: 48,
      margin: { top: 20, right: 10, bottom: 15, left: 10 },
      theme: 'grid',
      showHead: 'everyPage',
      showFoot: 'lastPage',
      styles: {
        font: 'helvetica',
        fontSize: columns.length > 9 ? 6.5 : (columns.length > 6 ? 7.5 : 8.5),
        cellPadding: columns.length > 9 ? 1.5 : 2,
        lineColor: [226, 232, 240],
        lineWidth: 0.15,
        textColor: [15, 23, 42]
      },
      headStyles: {
        fillColor: [16, 39, 70], // Navy
        textColor: [255, 255, 255],
        fontStyle: 'bold',
        halign: 'center',
        valign: 'middle'
      },
      footStyles: {
        fillColor: [226, 232, 240],
        textColor: [15, 23, 42],
        fontStyle: 'bold',
        valign: 'middle'
      },
      alternateRowStyles: {
        fillColor: [244, 248, 250] // Soft light-blue alternate
      },
      columnStyles,
      didDrawPage: (data) => {
        // Page Footer
        const str = `Page ${data.pageNumber}`
        doc.setFontSize(7)
        doc.setFont('helvetica', 'normal')
        doc.setTextColor(100, 116, 139)

        // Left footer: Company & Timestamp
        doc.text(
          `iSysware HRMS | Statement Ref: ${report.id} | Generated: ${metadata?.generatedAtFormatted || ''}`,
          10,
          pageHeight - 8
        )

        // Center footer: Confidentiality
        doc.text(metadata?.confidentialityNotice || 'CONFIDENTIAL', pageWidth / 2, pageHeight - 8, {
          align: 'center'
        })

        // Right footer: Page X
        doc.text(str, pageWidth - 10, pageHeight - 8, { align: 'right' })
      }
    })

    return doc
  },

  /**
   * Generates and downloads the PDF file in browser
   */
  downloadPdf(reportResult) {
    const doc = this.buildPdfDocument(reportResult)

    const reportCode = (reportResult.report.name || 'Report').replace(/[^a-zA-Z0-9]/g, '_')
    const timestamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19)
    const filename = `iSysware_${reportCode}_${timestamp}.pdf`

    if (typeof window !== 'undefined' && typeof doc.save === 'function') {
      doc.save(filename)
    }

    return { filename, doc }
  }
}
